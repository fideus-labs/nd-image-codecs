"""Tests for the release scripts in `scripts/release/`.

These three scripts decide what version number reaches crates.io, PyPI, and
npm, and none of it is reversible — a published version cannot be replaced or
re-uploaded. That makes their failure modes unusually expensive for how little
code they are, and unusually hard to notice: `set-version.py` rewrites seven
file formats with text substitution, so the way it breaks is by *quietly*
matching the wrong line or missing one, and `publish-crates.py` decides which
crates to skip from a registry query that can fail in four different ways.

Everything that touches the filesystem runs against a synthetic repository
built in a temporary directory, never the real one. `set-version.py` locates
the repository root as `parents[2]` of its own path, so copying it to
`<tmp>/scripts/release/set-version.py` retargets it — which also means the real
`scripts/ci/check-package-versions.py` can be copied in alongside and used as
the oracle, exactly as it is in production.

Run with:

    uvx --with pytest --from pytest pytest scripts/tests -q

Requires: pytest. No network — the one script that talks to crates.io has its
transport replaced.
"""

from __future__ import annotations

import importlib.util
import json
import pathlib
import shutil
import subprocess
import sys
import textwrap
import types
import urllib.error

import pytest

REPO = pathlib.Path(__file__).resolve().parents[2]
RELEASE = REPO / "scripts" / "release"

# The fixture repository is deliberately *not* a copy of this one: it is the
# smallest tree that exercises every branch, including the two cases the real
# workspace does not currently have (a member pinning a literal version, and a
# `publish = false` member) and the one it must never lose (a third-party
# `"version"` key in package-lock.json that has to stay put).
FIXTURE_VERSION = "0.4.2"

CARGO_TOML = """\
[workspace]
resolver = "2"
members = [
    "crates/alpha",
    "crates/beta",
    "crates/nopub",
]

[workspace.package]
version = "0.4.2"
edition = "2024"

[workspace.dependencies]
# --- Internal crates -------------------------------------------------
alpha = { path = "crates/alpha", version = "0.4.2" }
# Key order reversed on purpose: the rewriter must not assume `path` first.
beta = { version = "0.4.2", path = "crates/beta" }
# A path dep with no version is intentional for unpublished members.
nopub = { path = "crates/nopub" }

# --- Third party ------------------------------------------------------
serde = { version = "1", features = ["derive"] }
"""

CARGO_LOCK = """\
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "alpha"
version = "0.4.2"
dependencies = [
 "serde",
]

[[package]]
name = "beta"
version = "0.4.2"
dependencies = [
 "alpha",
]

[[package]]
name = "nopub"
version = "0.4.2"

[[package]]
name = "serde"
version = "1.0.219"
source = "registry+https://github.com/rust-lang/crates.io-index"
"""

PYPROJECT = """\
[build-system]
requires = ["maturin>=1.7,<2.0"]
build-backend = "maturin"

[project]
name = "nd-image-codecs"
version = "0.4.2"
requires-python = ">=3.11"

[tool.maturin]
# A `version` key in another table must not be mistaken for the project's.
python-source = "python"
"""

INIT_PY = '''\
"""Package init."""

__all__ = ["__version__"]

try:
    __version__: str = _native_version()
except ImportError:
    __version__ = "0.4.2"
'''


def _member_manifest(name: str, *, literal_version: bool = False, publish: bool = True) -> str:
    version = f'version = "{FIXTURE_VERSION}"' if literal_version else "version.workspace = true"
    lines = ["[package]", f'name = "{name}"', version]
    if not publish:
        lines.append("publish = false")
    return "\n".join(lines) + "\n"


def _package_json(name: str) -> dict:
    return {"name": name, "version": FIXTURE_VERSION, "license": "MIT"}


def _package_lock() -> dict:
    return {
        "name": "@fideus-labs/nd-image-codecs",
        "version": FIXTURE_VERSION,
        "lockfileVersion": 3,
        "packages": {
            "": {"name": "@fideus-labs/nd-image-codecs", "version": FIXTURE_VERSION},
            # The property that matters most in this file: a third-party pin
            # that shares the key name and must not move.
            "node_modules/typescript": {"version": "5.6.0"},
            "node_modules/vitest": {"version": "2.0.0"},
        },
    }


def _write_json(path: pathlib.Path, document: dict) -> None:
    path.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


@pytest.fixture
def fake_repo(tmp_path: pathlib.Path) -> pathlib.Path:
    """A minimal repository the release scripts accept, at `FIXTURE_VERSION`."""
    root = tmp_path / "repo"
    (root / "scripts" / "release").mkdir(parents=True)
    (root / "scripts" / "ci").mkdir(parents=True)

    for script in ("set-version.py", "publish-crates.py"):
        shutil.copy2(RELEASE / script, root / "scripts" / "release" / script)
    # The oracle, copied verbatim: these tests assert the writer and the
    # production reader agree, not that the writer agrees with a restatement
    # of itself.
    shutil.copy2(
        REPO / "scripts" / "ci" / "check-package-versions.py",
        root / "scripts" / "ci" / "check-package-versions.py",
    )

    (root / "Cargo.toml").write_text(CARGO_TOML, encoding="utf-8")
    (root / "Cargo.lock").write_text(CARGO_LOCK, encoding="utf-8")
    for name, literal, publish in (("alpha", False, True), ("beta", True, True), ("nopub", False, False)):
        crate = root / "crates" / name
        crate.mkdir(parents=True)
        (crate / "Cargo.toml").write_text(
            _member_manifest(name, literal_version=literal, publish=publish), encoding="utf-8"
        )

    py = root / "bindings" / "python" / "nd-image-codecs"
    (py / "python" / "nd_image_codecs").mkdir(parents=True)
    (py / "pyproject.toml").write_text(PYPROJECT, encoding="utf-8")
    (py / "python" / "nd_image_codecs" / "__init__.py").write_text(INIT_PY, encoding="utf-8")

    ts = root / "bindings" / "typescript"
    ts.mkdir(parents=True)
    _write_json(ts / "package.json", _package_json("@fideus-labs/nd-image-codecs"))
    _write_json(ts / "package-lock.json", _package_lock())

    js = root / "bindings" / "javascript"
    js.mkdir(parents=True)
    _write_json(js / "package.json", _package_json("nd-image-codecs"))

    return root


def run_set_version(repo: pathlib.Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(repo / "scripts" / "release" / "set-version.py"), *args],
        capture_output=True,
        text=True,
        check=False,
    )


def load(path: pathlib.Path, name: str) -> types.ModuleType:
    """Import a script whose filename is not a valid module name."""
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


