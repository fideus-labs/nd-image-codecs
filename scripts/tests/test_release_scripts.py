def _fake_urlopen(payload=None, *, status=None, error=None, body=None):
    """Stand in for `urllib.request.urlopen`.

    `payload` is serialized as the response body; `status` raises an HTTPError;
    `error` raises it directly; `body` returns raw bytes that may not be JSON.
    """
    class Response:
        def read(self):
            return body if body is not None else json.dumps(payload).encode()

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

    def opener(request, timeout=None):
        if error is not None:
            raise error
        if status is not None:
            raise urllib.error.HTTPError(request.full_url, status, "boom", {}, None)
        return Response()

    return opener


def test_published_versions_reads_the_registry(publish_crates, monkeypatch):
    monkeypatch.setattr(
        publish_crates.urllib.request,
        "urlopen",
        _fake_urlopen({"versions": [{"num": "0.1.0"}, {"num": "0.2.0"}]}),
    )
    assert publish_crates.published_versions("alpha") == {"0.1.0", "0.2.0"}


def test_published_versions_treats_404_as_unclaimed(publish_crates, monkeypatch):
    monkeypatch.setattr(publish_crates.urllib.request, "urlopen", _fake_urlopen(status=404))
    assert publish_crates.published_versions("brand-new") == set()


