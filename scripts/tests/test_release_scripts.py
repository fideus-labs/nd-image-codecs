@pytest.mark.parametrize(
    ("tag", "version", "prerelease", "npm_tag"),
    [
        ("v0.2.0", "0.2.0", "false", "latest"),
        ("v1.0.0", "1.0.0", "false", "latest"),
        ("v0.0.0", "0.0.0", "false", "latest"),
        ("v10.20.30", "10.20.30", "false", "latest"),
        ("v1.0.0-rc.1", "1.0.0-rc.1", "true", "next"),
        ("v0.2.0-alpha", "0.2.0-alpha", "true", "next"),
        ("v2.0.0-beta.11", "2.0.0-beta.11", "true", "next"),
    ],
)
def test_parse_tag_accepts_release_tags(tag, version, prerelease, npm_tag, tmp_path):
    output = tmp_path / "github-output"
    result = subprocess.run(
        [sys.executable, str(RELEASE / "parse-tag.py"), tag],
        capture_output=True,
        text=True,
        check=False,
        env={"PATH": "/usr/bin:/bin", "GITHUB_OUTPUT": str(output)},
    )
    assert result.returncode == 0, result.stderr
    written = dict(line.split("=", 1) for line in output.read_text().splitlines())
    assert written == {
        "version": version,
        "tag": tag,
        "prerelease": prerelease,
        "npm-tag": npm_tag,
    }


@pytest.mark.parametrize(
    "tag",
    [
        "v0.2",  # not three components
        "v0.2.0.1",  # four
        "0.2.0",  # no `v`
        "vendor-bump",  # matches the `v*` trigger, is not a release
        "v2-experiment",
        "v1.2.3+build",  # legal SemVer; unpublishable on PyPI and npm
        "v1.2.3-rc.1+build",
        "v01.2.3",  # leading zero
        "v1.2.3 ",  # stray whitespace is stripped, then still fine — see below
        "",
        "v",
        "vx.y.z",
    ],
)
def test_parse_tag_rejects_everything_else(tag, tmp_path):
    output = tmp_path / "github-output"
    result = subprocess.run(
        [sys.executable, str(RELEASE / "parse-tag.py"), tag],
        capture_output=True,
        text=True,
        check=False,
        env={"PATH": "/usr/bin:/bin", "GITHUB_OUTPUT": str(output)},
    )
    if tag.strip() == "v1.2.3":
        # Surrounding whitespace is stripped rather than rejected; a tag cannot
        # contain it, but a shell can add it.
        assert result.returncode == 0
        return
    assert result.returncode == 2, f"{tag!r} was accepted: {result.stdout}"
    assert not output.exists(), "a rejected tag must not write workflow outputs"


def test_parse_tag_prints_without_github_output():
    """The script is also a human-readable check, run by hand on a tag."""
    result = subprocess.run(
        [sys.executable, str(RELEASE / "parse-tag.py"), "v3.1.4"],
        capture_output=True,
        text=True,
        check=False,
        env={"PATH": "/usr/bin:/bin"},
    )
    assert result.returncode == 0
    assert "3.1.4" in result.stdout
    assert "latest" in result.stdout


# ------------------------------------------------------------- set-version.py


def test_set_version_writes_every_location(fake_repo):
    result = run_set_version(fake_repo, "1.5.0")
    assert result.returncode == 0, result.stderr

    # The production reader is the assertion: it parses all seven files from
    # scratch and fails if any of the 23 literals disagrees.
    assert "all " in result.stdout and "read 1.5.0" in result.stdout

    manifest = (fake_repo / "Cargo.toml").read_text()
    assert 'version = "1.5.0"' in manifest
    assert 'alpha = { path = "crates/alpha", version = "1.5.0" }' in manifest
    assert 'beta = { version = "1.5.0", path = "crates/beta" }' in manifest
    # A path dep with no `version` stays that way — adding one would make the
    # crate unpublishable.
    assert 'nopub = { path = "crates/nopub" }' in manifest
    # A third-party requirement is not a version literal to bump.
    assert 'serde = { version = "1", features = ["derive"] }' in manifest

    # A member that spells out its own version rather than inheriting.
    assert 'version = "1.5.0"' in (fake_repo / "crates" / "beta" / "Cargo.toml").read_text()
    assert "version.workspace = true" in (fake_repo / "crates" / "alpha" / "Cargo.toml").read_text()

    assert '__version__ = "1.5.0"' in (
        fake_repo / "bindings/python/nd-image-codecs/python/nd_image_codecs/__init__.py"
    ).read_text()


def test_set_version_leaves_third_party_lock_pins_alone(fake_repo):
    """The failure this guards is silent and total.

    `Cargo.lock` and `package-lock.json` are mostly third-party pins that share
    the key name being rewritten. Moving one produces a lockfile that resolves
    to a version that does not exist.
    """
    assert run_set_version(fake_repo, "2.0.0").returncode == 0

    lock = (fake_repo / "Cargo.lock").read_text()
    assert 'name = "serde"\nversion = "1.0.219"' in lock
    assert lock.count('version = "2.0.0"') == 3  # alpha, beta, nopub — and nothing else
    assert lock.startswith("# This file is automatically @generated by Cargo.")

    npm_lock = json.loads((fake_repo / "bindings/typescript/package-lock.json").read_text())
    assert npm_lock["version"] == "2.0.0"
    assert npm_lock["packages"][""]["version"] == "2.0.0"
    assert npm_lock["packages"]["node_modules/typescript"]["version"] == "5.6.0"
    assert npm_lock["packages"]["node_modules/vitest"]["version"] == "2.0.0"


